import Transaction from '../models/Transaction.js';
import RecurringTransaction from '../models/RecurringTransaction.js';

/**
 * Calculates the next occurrence date for a given frequency.
 * Monthly uses a clamped day-of-month so 31 Jan + 1 month -> 28/29 Feb.
 */
export function advanceDate(date, frequency) {
  const base = new Date(date);

  if (frequency === 'daily') {
    const next = new Date(base);
    next.setUTCDate(next.getUTCDate() + 1);
    return next;
  }

  if (frequency === 'weekly') {
    const next = new Date(base);
    next.setUTCDate(next.getUTCDate() + 7);
    return next;
  }

  if (frequency === 'monthly') {
    const day = base.getUTCDate();
    const next = new Date(base);
    next.setUTCDate(1);
    next.setUTCMonth(next.getUTCMonth() + 1);
    const daysInMonth = new Date(
      Date.UTC(next.getUTCFullYear(), next.getUTCMonth() + 1, 0)
    ).getUTCDate();
    next.setUTCDate(Math.min(day, daysInMonth));
    return next;
  }

  // Unknown frequency: return null so the loop terminates safely.
  return null;
}

function buildNote(recurring) {
  const combined = recurring.note
    ? `${recurring.title} — ${recurring.note}`
    : recurring.title;
  return combined.slice(0, 300);
}

const MAX_OCCURRENCES_PER_RUN = 500;

/**
 * Processes every active recurring transaction whose `nextDueDate` is due.
 *
 * Idempotency:
 *  - Each generated Transaction stores `recurringSourceId` + `recurringOccurrenceDate`.
 *  - The Transaction model has a UNIQUE partial index on those two fields, so a
 *    second/concurrent run that tries to create the same occurrence fails with a
 *    duplicate-key error (code 11000) and is safely skipped.
 *
 * Catch-up:
 *  - Because it walks `nextDueDate` forward in a loop, missed occurrences
 *    (e.g. while the server was offline) are generated on the next run.
 */
export async function processDueRecurringTransactions({
  userId = null,
  now = new Date()
} = {}) {
  const filter = {
    status: 'active',
    nextDueDate: { $ne: null, $lte: now }
  };

  if (userId) filter.userId = userId;

  const dueList = await RecurringTransaction.find(filter);

  let created = 0;
  let failed = 0;

  for (const recurring of dueList) {
    let occurrence = recurring.nextDueDate;
    let guard = 0;

    while (
      occurrence &&
      occurrence <= now &&
      guard < MAX_OCCURRENCES_PER_RUN
    ) {
      guard += 1;

      try {
        await Transaction.create({
          userId: recurring.userId,
          type: recurring.type,
          amountCents: recurring.amountCents,
          categoryId: recurring.categoryId,
          date: occurrence,
          paymentMode: 'Other',
          note: buildNote(recurring),
          isRecurring: false,
          recurrence: null,
          walletId: recurring.walletId || null,
          // Idempotency markers (unique partial index in Transaction model).
          recurringSourceId: recurring._id,
          recurringOccurrenceDate: occurrence
        });

        created += 1;
      } catch (error) {
        if (error.code === 11000) {
          // This occurrence was already generated by a previous/parallel run.
        } else {
          failed += 1;
          console.error(
            'Failed to generate recurring occurrence:',
            error.message
          );
          break;
        }
      }

      const next = advanceDate(occurrence, recurring.frequency);

      // Respect the end date: stop generating once we pass it.
      if (recurring.endDate && next && next > recurring.endDate) {
        occurrence = null;
        break;
      }

      occurrence = next;
    }

    recurring.nextDueDate = occurrence; // null => schedule finished
    await recurring.save();
  }

  return {
    checked: dueList.length,
    created,
    failed
  };
}

let schedulerTimer = null;

/**
 * Starts a lightweight in-process scheduler that:
 *  - runs once immediately (so overdue items after a restart are caught up), and
 *  - then re-runs on a fixed interval.
 *
 * This reuses the project's existing scheduling approach (setInterval, no new
 * dependency) and does not create a second scheduler mechanism.
 */
export function startRecurringScheduler(intervalMs = 60000) {
  if (schedulerTimer) return schedulerTimer;

  const run = () => {
    processDueRecurringTransactions().catch((error) =>
      console.error('Recurring scheduler error:', error.message)
    );
  };

  run();

  schedulerTimer = setInterval(run, intervalMs);

  // Do not keep the process alive only because of this timer.
  if (typeof schedulerTimer.unref === 'function') {
    schedulerTimer.unref();
  }

  return schedulerTimer;
}
